// Sample JavaScript file for testing Copilot workflow

function greet(name) {
  const who = name || 'World';
  return `Hello, ${who}!`;
}

function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}

function multiply(a, b) {
  return a * b;
}

module.exports = { greet, add, subtract, multiply };
